//! Versioned `.aissence` interchange document.
//!
//! The document keeps model input (`source`) separate from generated output
//! (`summary`). This makes an unsummarized file a complete upload unit and
//! lets the server return a small summary delta for the client to merge.

use std::collections::BTreeSet;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::git::ProjectMetadata;
use crate::model::{
    AgentUsage, CommitFileChange, CommitGroup, CommitStats, CommitSummary, MessageSummary,
    TokenCount,
};

pub const DOCUMENT_VERSION: u32 = 2;
pub const SANITIZER_VERSION: u32 = 2;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct AissenceProject {
    /// Stable random identifier generated by the first local analysis.
    pub source_id: Uuid,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub repository: Option<String>,
}

impl AissenceProject {
    pub fn new(metadata: Option<ProjectMetadata>) -> Self {
        let metadata = metadata.unwrap_or_default();
        Self {
            source_id: Uuid::new_v4(),
            name: metadata.name,
            repository: metadata.repository,
        }
    }

    pub fn refresh_metadata(&mut self, metadata: Option<ProjectMetadata>) {
        let Some(metadata) = metadata else { return };
        if metadata.name.is_some() {
            self.name = metadata.name;
        }
        if metadata.repository.is_some() {
            self.repository = metadata.repository;
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CommitSource {
    pub messages: Vec<MessageSummary>,
    #[serde(default)]
    pub agents: Vec<AgentUsage>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tokens: Option<TokenCount>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AissenceCommit {
    pub commit_hash: String,
    pub source_digest: String,
    pub sanitizer_version: u32,
    pub title: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub body: Option<String>,
    pub date: DateTime<Utc>,
    pub stats: CommitStats,
    #[serde(default)]
    pub files: Vec<CommitFileChange>,
    pub source: CommitSource,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub summary: Option<CommitSummary>,
}

impl AissenceCommit {
    pub fn from_group(group: &CommitGroup) -> Option<Self> {
        let commit = group.commit.as_ref()?;
        let source = CommitSource {
            messages: crate::summarize::source_messages(group),
            agents: crate::model::agents_for(group),
            tokens: group.token_usage(),
        };
        let mut value = Self {
            commit_hash: commit.id.clone(),
            source_digest: String::new(),
            sanitizer_version: SANITIZER_VERSION,
            title: commit.summary.clone(),
            body: commit.body.clone(),
            date: commit.time,
            stats: commit.stats,
            files: commit.files.clone(),
            source,
            summary: group.summary.clone(),
        };
        crate::redact::Redactor::global().redact_commit(&mut value);
        Some(value)
    }

    pub fn calculate_source_digest(&self) -> String {
        #[derive(Serialize)]
        struct DigestInput<'a> {
            sanitizer_version: u32,
            commit_hash: &'a str,
            title: &'a str,
            body: &'a Option<String>,
            date: DateTime<Utc>,
            stats: CommitStats,
            files: &'a [CommitFileChange],
            source: &'a CommitSource,
        }

        let bytes = serde_json::to_vec(&DigestInput {
            sanitizer_version: self.sanitizer_version,
            commit_hash: &self.commit_hash,
            title: &self.title,
            body: &self.body,
            date: self.date,
            stats: self.stats,
            files: &self.files,
            source: &self.source,
        })
        .expect("serializing aissence digest input cannot fail");
        format!("sha256:{}", hex::encode(Sha256::digest(bytes)))
    }

    pub fn digest_is_valid(&self) -> bool {
        self.source_digest == self.calculate_source_digest()
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AissenceDocument {
    pub version: u32,
    pub project: AissenceProject,
    pub commits: Vec<AissenceCommit>,
    #[serde(default)]
    pub ignored: BTreeSet<String>,
}

impl AissenceDocument {
    pub fn empty(project: AissenceProject) -> Self {
        Self {
            version: DOCUMENT_VERSION,
            project,
            commits: Vec::new(),
            ignored: BTreeSet::new(),
        }
    }

    pub fn validate_version(&self) -> Result<(), String> {
        if self.version == DOCUMENT_VERSION {
            Ok(())
        } else {
            Err(format!(
                "unsupported .aissence version {}; expected {}",
                self.version, DOCUMENT_VERSION
            ))
        }
    }

    pub fn delta(&self, hashes: &BTreeSet<String>) -> Self {
        Self {
            version: self.version,
            project: self.project.clone(),
            commits: self
                .commits
                .iter()
                .filter(|commit| hashes.contains(&commit.commit_hash))
                .cloned()
                .collect(),
            ignored: BTreeSet::new(),
        }
    }

    pub fn merge_summaries(&mut self, delta: &Self) -> usize {
        let mut merged = 0;
        for incoming in &delta.commits {
            let Some(mut summary) = incoming.summary.clone() else {
                continue;
            };
            if let Some(local) = self.commits.iter_mut().find(|local| {
                local.commit_hash == incoming.commit_hash
                    && local.source_digest == incoming.source_digest
            }) {
                if let Some(existing) = &local.summary
                    && existing.messages.len() == summary.messages.len()
                {
                    for (incoming, existing) in summary.messages.iter_mut().zip(&existing.messages)
                    {
                        if incoming.subscriber_summary.is_none() {
                            incoming.subscriber_summary = existing.subscriber_summary.clone();
                        }
                    }
                    let mut failures = summary.prompt_failures.clone();
                    for failure in &existing.prompt_failures {
                        if summary
                            .messages
                            .get(failure.message_index)
                            .is_some_and(|message| message.subscriber_summary.is_none())
                            && !failures
                                .iter()
                                .any(|incoming| incoming.message_index == failure.message_index)
                        {
                            failures.push(failure.clone());
                        }
                    }
                    summary.prompt_failures = failures;
                }
                summary.prompt_failures.retain(|failure| {
                    summary
                        .messages
                        .get(failure.message_index)
                        .is_some_and(|message| message.subscriber_summary.is_none())
                });
                local.summary = Some(summary);
                merged += 1;
            }
        }
        merged
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn summary_does_not_change_source_digest() {
        let mut commit = AissenceCommit {
            commit_hash: "a".repeat(40),
            source_digest: String::new(),
            sanitizer_version: SANITIZER_VERSION,
            title: "test".into(),
            body: None,
            date: DateTime::UNIX_EPOCH,
            stats: CommitStats::default(),
            files: Vec::new(),
            source: CommitSource {
                messages: Vec::new(),
                agents: Vec::new(),
                tokens: None,
            },
            summary: None,
        };
        let before = commit.calculate_source_digest();
        commit.summary = Some(CommitSummary::default());
        assert_eq!(before, commit.calculate_source_digest());
    }

    #[test]
    fn nested_unknown_fields_are_rejected() {
        let value = serde_json::json!({
            "version": DOCUMENT_VERSION,
            "project": { "source_id": Uuid::nil() },
            "commits": [{
                "commit_hash": "a".repeat(40),
                "source_digest": format!("sha256:{}", "0".repeat(64)),
                "sanitizer_version": SANITIZER_VERSION,
                "title": "test",
                "date": "1970-01-01T00:00:00Z",
                "stats": {
                    "files_changed": 0,
                    "lines_added": 0,
                    "lines_deleted": 0,
                    "unexpected": true
                },
                "files": [],
                "source": { "messages": [], "agents": [] }
            }],
            "ignored": []
        });
        assert!(serde_json::from_value::<AissenceDocument>(value).is_err());
    }

    #[test]
    fn summary_delta_preserves_partial_local_prompt_work_until_remote_completion() {
        let project = AissenceProject::new(None);
        let message = MessageSummary {
            kind: crate::model::MessageKind::UserWrote,
            subscriber_summary: None,
            content: Some("A prompt".into()),
            changes: Vec::new(),
            timestamp: None,
            tokens: None,
        };
        let mut commit = AissenceCommit {
            commit_hash: "a".repeat(40),
            source_digest: String::new(),
            sanitizer_version: SANITIZER_VERSION,
            title: "test".into(),
            body: None,
            date: DateTime::UNIX_EPOCH,
            stats: CommitStats::default(),
            files: Vec::new(),
            source: CommitSource {
                messages: vec![message.clone()],
                agents: Vec::new(),
                tokens: None,
            },
            summary: Some(CommitSummary {
                messages: vec![message.clone()],
                prompt_failures: vec![crate::model::PromptSummaryFailure {
                    message_index: 0,
                    model: "small/model".into(),
                    error: "empty response".into(),
                    attempted_at: DateTime::UNIX_EPOCH,
                }],
                ..CommitSummary::default()
            }),
        };
        commit.source_digest = commit.calculate_source_digest();
        let mut local = AissenceDocument {
            version: DOCUMENT_VERSION,
            project: project.clone(),
            commits: vec![commit.clone()],
            ignored: BTreeSet::new(),
        };
        let mut incoming = commit;
        incoming.summary = Some(CommitSummary {
            messages: vec![message],
            ..CommitSummary::default()
        });
        let mut delta = AissenceDocument {
            version: DOCUMENT_VERSION,
            project,
            commits: vec![incoming],
            ignored: BTreeSet::new(),
        };

        assert_eq!(local.merge_summaries(&delta), 1);
        assert_eq!(
            local.commits[0]
                .summary
                .as_ref()
                .unwrap()
                .prompt_failures
                .len(),
            1
        );

        delta.commits[0].summary.as_mut().unwrap().messages[0].subscriber_summary =
            Some("A completed summary.".into());
        assert_eq!(local.merge_summaries(&delta), 1);
        let summary = local.commits[0].summary.as_ref().unwrap();
        assert_eq!(
            summary.messages[0].subscriber_summary.as_deref(),
            Some("A completed summary.")
        );
        assert!(summary.prompt_failures.is_empty());
    }
}
